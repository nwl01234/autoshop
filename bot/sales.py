def faq_sections() -> list[tuple[str, str]]:
    blocks, title, buf = [], "", []
    for line in FAQ_PATH.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            if title:
                blocks.append((title, " ".join(buf)))
            title, buf = line[3:].strip(), []
        elif title:
            buf.append(line)
    if title:
        blocks.append((title, " ".join(buf)))
    return blocks


def _theme(q: str) -> str | None:
    ql = (q or "").lower().replace("ё", "е")
    for name, pattern in THEMES:
        if re.search(pattern, ql):
            return name
    return None


def _product(q: str):
    t = (q or "").lower().replace("ё", "е")
    pid = guess_product(t)
    return storage.product(pid) if pid else None


def _tokens(q: str) -> list[str]:
    return re.findall(r"\w{3,}", (q or "").lower().replace("ё", "е"))


def _best_section(q: str) -> tuple[str, str] | None:
    toks = _tokens(q)
    if not toks:
        return None
    hay_words: dict[tuple[str, str], set[str]] = {}
    for title, body in faq_sections():
        hay_words[(title, body)] = set(re.findall(r"\w{3,}", (title + " " + body).lower().replace("ё", "е")))
    best, score = None, 0
    for key, words in hay_words.items():
        s = sum(1 for t in toks if t in words or any(SequenceMatcher(None, t, w).ratio() >= 0.85 for w in words))
        if s > score:
            best, score = key, s
    return best


def _price_list() -> str:
    lines = ["💵 <b>Прайс-лист AutoShop</b> (разовая оплата, без подписок):"]
    for p in storage.products():
        lines.append(f"{p['emoji']} {p['name']} — {p['price']} ₽ {p['unit']}")
    lines.append("\nСкидок нет — в цену уже входит внедрение и поддержка.")
    lines.append("👉 Скажите «сколько стоит <товар>» — или просто «в корзину».")
    return "\n".join(lines)


def answer(q: str) -> str | None:
    """Ответ на любой вопрос: тема (приоритет) → товар → база знаний → None."""
    ql = (q or "").lower().replace("ё", "е")
    theme = _theme(ql)

    # 1) приоритетные темы: продажа НЕ зависит от товара
    if theme in THEME_REPLIES:
        return THEME_REPLIES[theme]

    prod = _product(ql)
    if prod:
        if theme == "цена":
            return (f"{prod['emoji']} «{prod['name']}» — {prod['price']} ₽ {prod['unit']}.\n"
                    "Разовая оплата, без подписок и скрытых платежей. Скидок нет — цена уже "
                    "включает внедрение и поддержку.\n\n"
                    "👉 Напиши «в корзину» — оформим за минуту.")
        if theme == "сроки":
            return (f"⏱ «{prod['name']}» внедряется 7–10 дней:\n"
                    "— сегодня согласуем сценарий,\n— за 2–3 дня покажу живое демо,\n— далее — сдача.\n\n"
                    "👉 Стартуем?")
        brief = "; ".join(prod["features"][:2])
        return (f"{prod['emoji']} <b>{prod['name']}</b>\n{prod['tagline']}\n"
                f"Умеет: {brief}.\n💵 {prod['price']} ₽ {prod['unit']}\n\n"
                "👉 Скажи «в корзину» — оформим, или задай вопрос по делу.")

    # 2) цена/сроки без конкретного товара → прайс-лист / общий срок
    if theme == "цена":
        return _price_list()
    if theme == "сроки":
        return ("⏱ Все проекты внедряются за 7–10 дней: сценарий сегодня → демо за 2–3 дня → сдача.\n\n"
                "👉 Скажи, какой проект берём — посчитаю точный срок под ваш объём.")

    # приветствие
    if re.search(r"^привет|здравств|добры|^ку$|^hi$|^hello", ql):
        return ("Привет 👋 Я — продавец AutoShop.\n"
                "Внутри — реальные работающие проекты: CRM, голосовой ИИ-оператор, боты и AI-интеграция.\n"
                "Скажи: «сколько стоит …» или «нужен…» — подскажу и доведу до оплаты.")

    sec = _best_section(q)
    if sec:
        title, body = sec
        body = re.sub(r"\s+", " ", body).strip()
        return f"💬 <b>{title}</b>\n{body}\n\n👉 Что из этого интересно? Могу добавить в корзину или показать демо."
    return None


